# Writes tools/board/charm_data.scad from the charm mockup (tools/board/mockups/charm3.py), so the CAD
# engraves exactly what the mockup shows: curved names (one glyph each), star dots, border ticks, the
# faction symbols, copper gaps / brackets, Coruscant's lane break and the orbit nebulae.
# python tools/board/make_charm_data.py   (re-run after any change to charm3.py, then re-render the halves)
# Mockup coords: angle 0 = east, +90 = SOUTH, y down. OpenSCAD: y up -> (x, -y), angle -> -angle.
import math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
MOCK = os.path.join(HERE, "mockups", "charm3.py")
g = {"__file__": MOCK, "__name__": "charm3"}
cwd = os.getcwd(); os.chdir(os.path.dirname(MOCK))
exec(open(MOCK, encoding="utf-8").read(), g)
os.chdir(cwd)
g["board2"](False, "orbits")
EXP = g["EXP"]; W = g["W"]; pol = g["pol"]

from PIL import ImageFont
FONT = ImageFont.truetype(r"C:\Program Files\OpenSCAD (Nightly)\fonts\Liberation-2.00.1\ttf\LiberationSans-Bold.ttf", 1000)
EM_PER_SIZE = 9.5548 / 0.688 / 10   # OpenSCAD size 10 -> cap 9.55 mm; Liberation Bold cap = 0.688 em
def S(p): return (p[0], -p[1])
def f(x): return "%.3f" % x

glyphs = []
for r, a, txt, em, spacing, _ in EXP["labels"]:
    w = [FONT.getlength(c) / 1000 * em for c in txt]
    L = sum(w) + spacing * (len(txt) - 1)
    s = -L / 2
    for c, wc in zip(txt, w):
        mid = s + wc / 2; s += wc + spacing
        if c == " ": continue
        am = a - math.degrees(mid / r)          # the mockup path runs counter-clockwise on screen
        th = -am                                # OpenSCAD angle
        x, y = r * math.cos(math.radians(th)), r * math.sin(math.radians(th))
        glyphs.append('["%s", %s, %s, %s, %s]' % (c, f(x), f(y), f(th + 90), f(em / EM_PER_SIZE)))

stars = ['[%s, %s, %s]' % (f(x), f(-y), f(rr)) for x, y, rr in EXP["stars"]]
ticks = []
for a, L in EXP["ticks"]:
    p0, p1 = S(pol(146.9 - L, a)), S(pol(146.9, a))
    ticks.append('[%s, %s, %s, %s]' % (f(p0[0]), f(p0[1]), f(p1[0]), f(p1[1])))
ins = []
for i, wd in enumerate(W):
    if wd[3] < 0: continue
    q, r = g["insignia_place"](i)
    ins.append('[%d, %s, %s, %s, %s]' % (wd[3], f(q[0]), f(-q[1]), f(90 - wd[2]), f(r)))   # rot: screen (wa - 90) mirrored

# orbit nebulae as stroked polylines, broken round the fleet holes
neb = []
for n in g["NEB"]:
    c = pol(g["OUT"], n[0]); holes = g["nebula_holes"](n)
    for k, wdt, dash in ((1, 0.8, None), (0.72, 0.6, (2.0, 1.4)), (0.44, 0.6, (1.0, 1.2))):
        rx, ry = 17 * k, 12.5 * k
        pts = [(c[0] + rx * math.cos(2 * math.pi * j / 720), c[1] + ry * math.sin(2 * math.pi * j / 720)) for j in range(721)]
        # walk by arc length, emit dashes
        segs, cur, acc, on, lim = [], [], 0.0, True, (dash[0] if dash else 1e9)
        for j in range(len(pts)):
            p = pts[j]
            if j: acc += math.dist(pts[j - 1], p)
            blocked = any(math.dist(p, h) < 4.6 for h in holes)
            if dash and acc >= lim:
                on = not on; acc = 0.0; lim = dash[0] if on else dash[1]
                if cur: segs.append(cur); cur = []
            if on and not blocked: cur.append(p)
            elif cur: segs.append(cur); cur = []
        if cur: segs.append(cur)
        for sg in segs:
            if len(sg) >= 2:
                neb.append('[%s, [%s]]' % (f(wdt), ", ".join("[%s, %s]" % (f(x), f(-y)) for x, y in sg[::2] + ([sg[-1]] if len(sg) % 2 == 0 else []))))

a16, r16 = g["label_place"](16)
LS2 = g["LS2"]
out = os.path.join(HERE, "charm_data.scad")
with open(out, "w", encoding="utf-8", newline="\n") as fo:
    fo.write("// GENERATED by tools/board/make_charm_data.py from mockups/charm3.py -- do not hand-edit.\n")
    fo.write("CH_GLYPHS = [%s];\n" % ",\n  ".join(glyphs))
    fo.write("CH_STARS = [%s];\n" % ", ".join(stars))
    fo.write("CH_TICKS = [%s];\n" % ",\n  ".join(ticks))
    fo.write("CH_INSIGNIA = [%s];   // faction, x, y, rotation, radius\n" % ", ".join(ins))
    fo.write("CH_COPPER_GAPS = [%s];   // MOCKUP angles\n" % ", ".join("[%s, %s]" % (f(a), f(b)) for a, b in g["COPPER_GAPS"]))
    fo.write("CH_BRACKETS = [%s];\n" % ", ".join(f(b) for b in g["BRACKETS"]))
    fo.write("CH_LANE_BREAK = [%s, %s];   // Kijimi -> Coruscant lane: open between these radii (Coruscant's name)\n" % (f(r16 + 1.2), f(r16 - LS2 * 0.72 - 1.2)))
    fo.write("CH_NEB = [%s];   // stroke width, polyline\n" % ",\n  ".join(neb))
print(out, len(glyphs), "glyphs,", len(stars), "stars,", len(ticks), "ticks,", len(neb), "nebula strokes")
