"""3.1-dev.35: gzip the phone page (PAGE_HTML in web_server.cpp) into sf_page_gz.h so the table sends
~1/4 of the bytes (playtest 2026-11-08: phones on a busy Wi-Fi took seconds to load the ~280 KB page and
the table ran out of memory doing it). RUN AFTER EVERY PHONE-PAGE EDIT, before compiling:
    python tools/page/make_page_gz.py
If you forget, the table notices (the page's fingerprint differs from SF_PAGE_SRC_HASH) and serves the
plain page instead -- slower, never broken.
"""
import gzip, io, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'ShadowFleet_Prototype_02', 'web_server.cpp')
OUT = os.path.join(ROOT, 'ShadowFleet_Prototype_02', 'sf_page_gz.h')

text = open(SRC, encoding='utf-8').read()
# 3.1-dev.44: the page's own firmware version (PAGE_FW) follows version.h, so phones reload after a flash
fw = re.search(r'#define FIRMWARE_VERSION "([^"]+)"', open(os.path.join(ROOT, 'ShadowFleet_Prototype_02', 'version.h'), encoding='utf-8').read()).group(1)
new = re.sub(r"const PAGE_FW = '[^']*';", "const PAGE_FW = '" + fw + "';", text, count=1)
if new != text:
    open(SRC, 'w', encoding='utf-8', newline='\n').write(new)
    text = new
    print('PAGE_FW ->', fw)
start = text.index('static const char PAGE_HTML[] PROGMEM = R"HTML(') + len('static const char PAGE_HTML[] PROGMEM = R"HTML(')
end = text.index(')HTML";', start)
page = text[start:end].encode('utf-8')  # exactly the bytes the compiler stores (raw string, no escapes)

h = 2166136261
for b in page:
    h = ((h ^ b) * 16777619) & 0xFFFFFFFF

buf = io.BytesIO()
with gzip.GzipFile(fileobj=buf, mode='wb', compresslevel=9, mtime=0) as g:
    g.write(page)
gz = buf.getvalue()
assert gzip.decompress(gz) == page, 'round trip failed'

lines = ['// GENERATED by tools/page/make_page_gz.py from PAGE_HTML in web_server.cpp -- never hand-edit.',
         '// Re-run the script after every phone-page edit (the table falls back to the plain page if it is stale).',
         '#pragma once',
         '#include <stdint.h>',
         '#define SF_PAGE_SRC_LEN %d' % len(page),
         '#define SF_PAGE_SRC_HASH 0x%08Xu' % h,
         '#define SF_PAGE_GZ_LEN %d' % len(gz),
         '#define SF_PAGE_FW "%s"' % fw,  # 3.1-dev.112: checked against FIRMWARE_VERSION at compile time
         'static const uint8_t SF_PAGE_GZ[SF_PAGE_GZ_LEN] PROGMEM = {']
for i in range(0, len(gz), 24):
    lines.append('  ' + ', '.join('0x%02X' % b for b in gz[i:i + 24]) + ',')
lines.append('};')
open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
print('page %d bytes -> gzip %d bytes (%.0f%%), hash 0x%08X' % (len(page), len(gz), 100.0 * len(gz) / len(page), h))
