#!/usr/bin/perl
# Generates ShadowFleet_Prototype_02/negotiation_bank.cpp (v0.30.0; v0.30.1 adds
# the faction questions, the favor bank and the hostile lines). Sources:
#   questions.txt          the shared bank (any faction may ask)
#   faction_questions.txt  each faction's own questions (only once Affiliation is revealed)
#   favors.txt             the favor bank (N normal, L late) + hostile lines (H)
# Run from anywhere:  perl tools/negotiation/make_bank.pl   -- never hand-edit the .cpp.
# The shared questions come out sorted by tier (NEG_TIER_START / NEG_TIER_COUNT),
# then each faction's own questions (NEG_OWN_START / NEG_OWN_COUNT).
use strict;
use warnings;
use FindBin;

my %val = ('+' => 1, '-' => -1, '0' => 0);
my %tierNum = (EASY => 0, MEDIUM => 1, HARD => 2);
my %fac = (R => 0, E => 1, P => 2, C => 3);
my %facName = (R => 'FACTION_REBEL', E => 'FACTION_EMPIRE', P => 'FACTION_PYKE', C => 'FACTION_CRIMSON_DAWN');
my %check = (TAKE => 'PROMISE_TAKE_FACTION', WIN_PVP => 'PROMISE_WIN_PVP', NO_INVEST => 'PROMISE_NO_INVEST',
             NO_ATTACK => 'PROMISE_NO_ATTACK', HOLD => 'PROMISE_HOLD', TRIBUTE => 'PROMISE_TRIBUTE',
             WIN_BATTLE => 'PROMISE_WIN_BATTLE', TAKE_CORE => 'PROMISE_TAKE_CORE', HOLD_TWO => 'PROMISE_HOLD_TWO',
             CREDITS => 'NEG_FAVOR_CREDITS');

sub lines { my $f = shift; open my $h, '<', "$FindBin::Bin/$f" or die "$f: $!"; my @l = map { s/\r?\n$//r } <$h>; close $h; return grep { !/^\s*(#|$)/ } @l; }

# Shared questions.
my @q;
for (lines('questions.txt')) {
  if (/^Q (EASY|MEDIUM|HARD) \| (.+)$/) { push @q, { tier => $tierNum{$1}, own => -1, q => $2, r => [] }; next; }
  if (/^A (.+?) \| ([-+0]) ([-+0]) ([-+0]) ([-+0])$/) { die "reply before any question: $_\n" unless @q; push @{ $q[-1]{r} }, [ $1, map { $val{$_} } $2, $3, $4, $5 ]; next; }
  die "questions.txt: can't read: $_\n";
}
for my $x (@q) {
  die "question needs 3 replies: $x->{q}\n" unless @{ $x->{r} } == 3;
  my $askers = 0;
  for my $f (1 .. 4) { $askers++ if grep { $_->[$f] == 1 } @{ $x->{r} }; }
  die "nobody can ask: $x->{q}\n" unless $askers;
}
my $i = 0;
@q = map { $_->[1] } sort { $a->[1]{tier} <=> $b->[1]{tier} || $a->[0] <=> $b->[0] } map { [ $i++, $_ ] } @q;
my @start = (0, 0, 0); my @count = (0, 0, 0);
for my $k (0 .. $#q) { my $t = $q[$k]{tier}; $start[$t] = $k unless $count[$t]; $count[$t]++; }

# Each faction's own questions: one reaction per reply, from that faction only.
my @own;
for (lines('faction_questions.txt')) {
  if (/^F ([REPC]) \| (.+)$/) { push @own, { tier => 1, own => $fac{$1}, q => $2, r => [] }; next; }
  if (/^A (.+?) \| ([-+0])$/) {
    die "reply before any question: $_\n" unless @own;
    my @react = (0, 0, 0, 0); $react[ $own[-1]{own} ] = $val{$2};
    push @{ $own[-1]{r} }, [ $1, @react ]; next;
  }
  die "faction_questions.txt: can't read: $_\n";
}
for my $x (@own) { die "needs 3 replies: $x->{q}\n" unless @{ $x->{r} } == 3; }
@own = sort { $a->{own} <=> $b->{own} } @own;
my @ownStart = (0, 0, 0, 0); my @ownCount = (0, 0, 0, 0);
for my $k (0 .. $#own) { my $f = $own[$k]{own}; $ownStart[$f] = @q + $k unless $ownCount[$f]; $ownCount[$f]++; }

# Favors and hostile lines.
my (@fav, @hostile);
for (lines('favors.txt')) {
  if (/^H ([REPC]) \| (.+)$/) { push @hostile, [ $fac{$1}, $2 ]; next; }
  /^([NL]) ([REPC]) \| (\*?)(\w+)(?: (\w+))? \| (.+)$/ or die "favors.txt: can't read: $_\n";
  my ($late, $f, $hard, $chk, $arg, $text) = ($1 eq 'L' ? 1 : 0, $fac{$2}, $3 ? 1 : 0, $4, $5, $6);
  die "favors.txt: unknown check $chk\n" unless $check{$chk};
  my $a = !defined $arg ? -1 : $arg =~ /^\d+$/ ? $arg : $facName{$arg} // die "favors.txt: bad arg $arg\n";
  push @fav, { late => $late, f => $f, hard => $hard, check => $check{$chk}, arg => $a, text => $text };
}
@fav = sort { $a->{f} <=> $b->{f} || $a->{late} <=> $b->{late} } @fav;
@hostile = sort { $a->[0] <=> $b->[0] } @hostile;
my @hStart = (0, 0, 0, 0); my @hCount = (0, 0, 0, 0);
for my $k (0 .. $#hostile) { my $f = $hostile[$k][0]; $hStart[$f] = $k unless $hCount[$f]; $hCount[$f]++; }
for my $f (0 .. 3) {
  my @n = grep { $_->{f} == $f && !$_->{late} } @fav;
  my @l = grep { $_->{f} == $f && $_->{late} } @fav;
  die "faction $f needs a hard favor in both lists\n" unless (grep { $_->{hard} } @n) && (grep { $_->{hard} } @l);
  die "faction $f needs 3+ normal favors\n" unless @n >= 3;
  die "faction $f needs a CREDITS late favor and 2+ late deeds\n" unless (grep { $_->{check} eq 'NEG_FAVOR_CREDITS' } @l) && (grep { $_->{check} ne 'NEG_FAVOR_CREDITS' } @l) >= 2;
  die "faction $f has no hostile lines\n" unless $hCount[$f];
}

sub c { my $s = shift; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return "\"$s\""; }

my $out = "$FindBin::Bin/../../ShadowFleet_Prototype_02/negotiation_bank.cpp";
open my $o, '>', $out or die "$out: $!";
print $o "// GENERATED by tools/negotiation/make_bank.pl from tools/negotiation/questions.txt,\n";
print $o "// faction_questions.txt and favors.txt -- edit those and re-run, never this file.\n";
print $o "#include \"negotiation_bank.h\"\n#include \"game_state.h\"\n\n";
print $o "const NegQuestion NEG_BANK[] = {\n";
for my $x (@q, @own) {
  print $o "  { $x->{tier}, $x->{own}, " . c($x->{q}) . ",\n";
  print $o "    { " . join(",\n      ", map { c($_->[0]) } @{ $x->{r} }) . " },\n";
  print $o "    { " . join(", ", map { "{ " . join(", ", @$_[1 .. 4]) . " }" } @{ $x->{r} }) . " } },\n";
}
print $o "};\n";
print $o "const int NEG_BANK_COUNT = " . scalar(@q) . ";  // shared questions; the faction ones follow\n";
print $o "const int NEG_TIER_START[3] = { " . join(", ", @start) . " };\n";
print $o "const int NEG_TIER_COUNT[3] = { " . join(", ", @count) . " };\n";
print $o "const int NEG_OWN_START[4] = { " . join(", ", @ownStart) . " };\n";
print $o "const int NEG_OWN_COUNT[4] = { " . join(", ", @ownCount) . " };\n\n";
print $o "const NegFavor NEG_FAVOR_BANK[] = {\n";
print $o join("", map { "  { $_->{f}, $_->{late}, $_->{hard}, $_->{check}, $_->{arg}, " . c($_->{text}) . " },\n" } @fav);
print $o "};\nconst int NEG_FAVOR_COUNT = " . scalar(@fav) . ";\n\n";
print $o "const char *const NEG_HOSTILE_LINES[] = {\n" . join("", map { "  " . c($_->[1]) . ",\n" } @hostile) . "};\n";
print $o "const int NEG_HOSTILE_START[4] = { " . join(", ", @hStart) . " };\n";
print $o "const int NEG_HOSTILE_COUNT[4] = { " . join(", ", @hCount) . " };\n";
close $o;
printf "%d shared questions (easy %d, medium %d, hard %d) + %d faction questions, %d favors, %d hostile lines -> negotiation_bank.cpp\n",
  scalar(@q), @count, scalar(@own), scalar(@fav), scalar(@hostile);
