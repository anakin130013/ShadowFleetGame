def grid(txt):
    rows = txt.strip('\n').split('\n')
    w = max(len(r) for r in rows)
    return [r.ljust(w, '.') for r in rows]

def hexc(c): return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) + (255,)

def render(txt, pal, scale, outline=None):
    g = grid(txt); h, w = len(g), len(g[0]); pad = 1 if outline else 0
    img = Image.new('RGBA', ((w + 2 * pad) * scale, (h + 2 * pad) * scale), (0, 0, 0, 0)); px = img.load()
    def put(x, y, col):
        for dy in range(scale):
            for dx in range(scale): px[x * scale + dx, y * scale + dy] = col
    if outline:
        for y in range(h):
            for x in range(w):
                if g[y][x] != '.':
                    for ox, oy in ((1,0),(-1,0),(0,1),(0,-1)):
                        nx, ny = x + ox, y + oy
                        if not (0 <= nx < w and 0 <= ny < h) or g[ny][nx] == '.': put(nx + pad, ny + pad, hexc(outline))
    for y in range(h):
        for x in range(w):
            c = g[y][x]
            if c != '.': put(x + pad, y + pad, hexc(pal[c]))
    return img

