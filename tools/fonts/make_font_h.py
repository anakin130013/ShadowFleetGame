# 3.1-dev.4: turns the web font into a firmware header the table serves at /font.woff2.
#   python tools/fonts/make_font_h.py
# Space Grotesk (latin, variable weight) -- SIL Open Font License 1.1, see OFL.txt.
import os
here = os.path.dirname(os.path.abspath(__file__))
data = open(os.path.join(here, 'SpaceGrotesk-latin.woff2'), 'rb').read()
out = ['// GENERATED by tools/fonts/make_font_h.py -- do not edit by hand.',
       '// Space Grotesk (latin, variable 300-700), (c) 2020 The Space Grotesk Project Authors,',
       '// SIL Open Font License 1.1 (tools/fonts/OFL.txt). Served by the table at /font.woff2.',
       '#pragma once', '#include <stdint.h>', '#include <stddef.h>',
       'static const size_t SF_WEB_FONT_LEN = %d;' % len(data),
       'static const uint8_t SF_WEB_FONT[] = {']
for i in range(0, len(data), 24):
    out.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
out.append('};')
open(os.path.join(here, '..', '..', 'ShadowFleet_Prototype_02', 'sf_web_font.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote sf_web_font.h,', len(data), 'bytes')
