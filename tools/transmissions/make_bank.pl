#!/usr/bin/perl
# Builds ShadowFleet_Prototype_02/transmission_bank.cpp (the firmware's copy of
# the transmission bank) from the five text files here. The .txt files are
# the single source: edit a line there, then rerun
#   perl tools/transmissions/make_bank.pl
# and rebuild. Never hand-edit transmission_bank.cpp.
use strict; use warnings;
my $dir = $0; $dir =~ s{[^/\\]*$}{};
my $out = "${dir}../../ShadowFleet_Prototype_02/transmission_bank.cpp";

# Order must match transmission_bank.h (TxCause / TxBig) and game_state.h
# (FACTION_* and the PLANETS table).
my @FACTIONS = ([R => 'rebel'], [E => 'empire'], [P => 'pyke'], [C => 'crimson']);
my @CAUSES  = qw(took betray rival paid deal walkout kept broke courted);  # 3.1-dev.49 courted
my @MOMENTS = qw(firstblood seat core allied betrayal oathbreaker fleet lastround);
my @PLANETS = ('TATOOINE', 'HOTH', 'BESPIN', 'DAGOBAH', 'CORUSCANT', 'KESSEL',
               'OBA DIAH', 'DATHOMIR', 'CORELLIA', 'NABOO', 'ENDOR', 'KIJIMI',
               'YAVIN 4', 'MUSTAFAR', 'NAL HUTTA', 'CANTO BIGHT', 'KUAT');  # 2.0: 17 worlds
my %PIDX; @PIDX{@PLANETS} = (0 .. $#PLANETS);
my %FIDX = (R => 0, E => 1, P => 2, C => 3);

sub slurp { my $f = shift; open(my $h, '<', "$dir$f") or die "$f: $!"; local $/; my $t = <$h>; return $t; }
sub cstr { my $t = shift; $t =~ s/\\/\\\\/g; $t =~ s/"/\\"/g; die "non-ASCII: $t\n" if $t =~ /[^\x20-\x7E]/; return "\"$t\""; }

my (@lines, %cause, %planet, %big);
sub add { my ($list, $text) = @_; push @lines, $text; push @$list, $#lines; }

for my $fi (0 .. $#FACTIONS) {
  my $file = $FACTIONS[$fi][1];
  for (split /\r?\n/, slurp("$file.txt")) {
    next if /^\s*(#|$)/;
    if (/^@([A-Z ]+):\s*(.*)$/) {
      defined $PIDX{$1} or die "$file.txt: unknown planet $1\n";
      add(\@{$planet{$fi}{$PIDX{$1}}}, $2);
    } elsif (/^([a-z]+):\s*(.*)$/) {
      my $c = $1; grep { $_ eq $c } @CAUSES or die "$file.txt: unknown cause $c\n";
      add(\@{$cause{$fi}{$c}}, $2);
    } else { die "$file.txt: can't read: $_\n"; }
  }
}
for (split /\r?\n/, slurp('big.txt')) {
  next if /^\s*(#|$)/;
  /^([a-z]+) ([REPC]):\s*(.*)$/ or die "big.txt: can't read: $_\n";
  my $m = $1; grep { $_ eq $m } @MOMENTS or die "big.txt: unknown moment $m\n";
  add(\@{$big{$m}{$FIDX{$2}}}, $3);
}

# Lines were added bucket by bucket, so each bucket is a contiguous run.
sub bucket { my $l = shift; return '{ 0, 0 }' unless $l && @$l;
  for my $i (1 .. $#$l) {
    die "bucket not contiguous (keep each planet's lines together): $lines[$l->[0]]\n" if $l->[$i] != $l->[0] + $i;
  }
  return "{ $l->[0], " . scalar(@$l) . ' }';
}

open(my $o, '>', $out) or die "$out: $!";
print $o "// GENERATED by tools/transmissions/make_bank.pl from tools/transmissions/*.txt\n";
print $o "// -- do not edit; change the .txt files and rerun the script.\n";
print $o "#include \"transmission_bank.h\"\n\n";
print $o "const uint16_t TX_LINE_COUNT = " . scalar(@lines) . ";\n";
print $o "const char *const TX_LINES[] = {\n";
print $o "  " . cstr($_) . ",\n" for @lines;
print $o "};\n\n";
print $o "const TxBucket TX_CAUSE_BUCKETS[NUM_FACTIONS][TXC_COUNT] = {\n";
for my $fi (0 .. 3) { print $o "  { " . join(', ', map { bucket($cause{$fi}{$_}) } @CAUSES) . " },\n"; }
print $o "};\n\n";
print $o "const TxBucket TX_PLANET_BUCKETS[NUM_FACTIONS][NUM_PLANETS] = {\n";
for my $fi (0 .. 3) { print $o "  { " . join(', ', map { bucket($planet{$fi}{$_}) } 0 .. $#PLANETS) . " },\n"; }
print $o "};\n\n";
print $o "const TxBucket TX_BIG_BUCKETS[TXB_COUNT][NUM_FACTIONS] = {\n";
for my $m (@MOMENTS) { print $o "  { " . join(', ', map { bucket($big{$m}{$_}) } 0 .. 3) . " },  // $m\n"; }
print $o "};\n";
close $o;
print STDERR scalar(@lines) . " lines -> $out\n";
