# Generates ShadowFleet_Prototype_02/sf_web_icon.h: the home-screen app icon (180x180 PNG, original pixel art --
# a ringed planet over a starfield), served by the table at /icon.png for "Add to Home Screen".
#   python tools/icon/make_icon.py
import io, os, random
from PIL import Image, ImageDraw

N = 36            # pixel-art grid, scaled x5 to 180
img = Image.new('RGB', (N, N), (5, 7, 12))
d = ImageDraw.Draw(img)
random.seed(7)
for _ in range(40):  # stars
    x, y = random.randrange(N), random.randrange(N)
    c = random.choice([(90, 110, 130), (150, 170, 190), (232, 238, 245)])
    img.putpixel((x, y), c)
cx, cy, r = 18, 19, 10
for y in range(N):     # the planet: shaded from the top left
    for x in range(N):
        dx, dy = x - cx + 0.5, y - cy + 0.5
        if dx * dx + dy * dy <= r * r:
            t = (dx + dy) / (2 * r)
            band = (y // 3) % 2
            base = (95, 212, 255) if band else (60, 160, 210)
            k = max(0.35, 1 - (t + 0.5) * 0.7)
            img.putpixel((x, y), tuple(int(v * k) for v in base))
for x in range(N):     # the gold ring (in front below the middle, behind above)
    for y in range(N):
        dx, dy = (x - cx + 0.5) / 16, (y - cy + 0.5 + (x - cx) * 0.25) / 4.2
        e = dx * dx + dy * dy
        if 0.78 <= e <= 1.0:
            infront = (y - cy + (x - cx) * 0.25) > 0
            inside = (x - cx + 0.5) ** 2 + (y - cy + 0.5) ** 2 <= r * r
            if infront or not inside:
                img.putpixel((x, y), (255, 209, 102) if e > 0.88 else (200, 150, 60))
img = img.resize((180, 180), Image.NEAREST)
buf = io.BytesIO(); img.save(buf, 'PNG', optimize=True)
data = buf.getvalue()
out = os.path.join(os.path.dirname(__file__), '..', '..', 'ShadowFleet_Prototype_02', 'sf_web_icon.h')
rows = [', '.join('0x%02x' % b for b in data[i:i + 20]) for i in range(0, len(data), 20)]
with open(out, 'w', encoding='utf-8') as f:
    f.write('// GENERATED by tools/icon/make_icon.py -- do not edit by hand. The home-screen icon (original art), served at /icon.png.\n')
    f.write('#pragma once\n#include <stdint.h>\n')
    f.write('static const uint32_t SF_WEB_ICON_LEN = %d;\n' % len(data))
    f.write('static const uint8_t SF_WEB_ICON[] PROGMEM = {\n  ' + ',\n  '.join(rows) + '\n};\n')
img.save(os.path.join(os.path.dirname(__file__), 'icon_preview.png'))
print('wrote', out, len(data), 'bytes')
